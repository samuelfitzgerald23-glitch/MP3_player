U8G2_SSD1309_128X64_NONAME2_F_4W_HW_SPI u8g2(U8G2_R2, /*cs=*/ OLED_CS_PIN, /*dc=*/ OLED_DC_PIN, /*reset=*/ OLED_RESET_PIN);

bool sd_state;

void set_sdState(bool state) {
    sd_state = state;
}

static void drawScreen() {
    u8g2.setFontMode(1);
    u8g2.setBitmapMode(1);

    //draw the frame
    u8g2.drawRFrame(ZERO_X, ZERO_Y, 126, 62, 5);

    u8g2.drawXBMP(ICON_X_ZERO, ICON_Y_ZERO, 9, 9, image_gear_bits);

    u8g2.setCursor(TEXT_X_ZERO, TEXT_Y_ZERO);
    if(sd_state) {
        u8g2.print("SD card ready.");
    } else {
        u8g2.print("SD card not ready.");
    }
    u8g2.drawXBMP(64, ICON_Y_ZERO, 5, 8, image_Attention_bits);
    u8g2.drawXBMP(ART_X_ZERO, ART_Y_ZERO, 31, 31, image_reccord_icon_bits);
}

void OLED_init() {
    
    u8g2.begin();
    //pinMode(CS_PIN, OUTPUT);
    
    u8g2.setPowerSave(0);
    u8g2.clearBuffer();
    u8g2.setFontMode(1);
    u8g2.setBitmapMode(1);
    u8g2.setFont(u8g2_font_4x6_tr);
}

void OLED_task() {
    u8g2.clearBuffer();
    u8g2.firstPage();
    do {
        drawScreen();
    } while (u8g2.nextPage());
}